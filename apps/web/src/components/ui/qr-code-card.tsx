import { Download, Printer } from 'lucide-react';
import { apiUrl } from '@/lib/api';
import { cn } from '@/lib/utils';

export interface QRCodeCardProps {
  /** API path of the SVG QR, e.g. "/api/invitations/<token>/qr.svg". */
  svgUrl: string;
  pngUrl?: string;
  pdfUrl?: string;
  /** What the code encodes, shown under it so it can be typed if scanning fails. */
  caption?: string;
  title?: string;
  alt: string;
  size?: number;
  className?: string;
  /** Hide download buttons (e.g. inside a printable pass). */
  actions?: boolean;
}

/**
 * Plain black-on-white QR with a generous quiet zone (generated by the API), framed in gold.
 * The code itself is never styled, so scanning stays reliable.
 */
export function QRCodeCard({ svgUrl, pngUrl, pdfUrl, caption, title, alt, size = 220, className, actions = true }: QRCodeCardProps) {
  return (
    <figure className={cn('inline-flex flex-col items-center gap-3', className)}>
      {title && <figcaption className="text-xs font-medium uppercase tracking-[0.2em] text-gold-rich">{title}</figcaption>}
      <div className="rounded-2xl bg-white p-3 ring-1 ring-gold/50 shadow-soft">
        <img src={apiUrl(svgUrl)} alt={alt} width={size} height={size} className="block" style={{ width: size, height: size }} />
      </div>
      {caption && <p className="max-w-[260px] break-all text-center font-mono text-xs text-muted">{caption}</p>}
      {actions && (pngUrl || pdfUrl) && (
        <div className="no-print flex flex-wrap justify-center gap-2">
          {pngUrl && (
            <a href={apiUrl(pngUrl)} download className="inline-flex h-9 items-center gap-1.5 rounded-full border border-navy/15 px-3 text-xs font-medium text-navy hover:border-gold">
              <Download className="size-3.5" aria-hidden /> PNG
            </a>
          )}
          <a href={apiUrl(svgUrl)} download className="inline-flex h-9 items-center gap-1.5 rounded-full border border-navy/15 px-3 text-xs font-medium text-navy hover:border-gold">
            <Download className="size-3.5" aria-hidden /> SVG
          </a>
          {pdfUrl && (
            <a href={apiUrl(pdfUrl)} target="_blank" rel="noopener" className="inline-flex h-9 items-center gap-1.5 rounded-full border border-navy/15 px-3 text-xs font-medium text-navy hover:border-gold">
              <Printer className="size-3.5" aria-hidden /> Print PDF
            </a>
          )}
        </div>
      )}
    </figure>
  );
}
