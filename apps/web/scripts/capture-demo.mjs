#!/usr/bin/env node
/**
 * Captures the sample content the public site falls back to when the API cannot be reached.
 *
 * Reads the public pages' data from a running API (with demo content loaded), copies the thumb
 * and medium image of every photo into apps/web/public/demo/, points the data at those copies
 * and writes apps/web/src/demo/fixtures.ts. Videos are left out. Fields that look like tokens
 * are dropped.
 *
 * Usage: node apps/web/scripts/capture-demo.mjs [api-base-url]   (default http://localhost:4100)
 */
import fs from 'node:fs';
import path from 'node:path';

const base = (process.argv[2] ?? 'http://localhost:4100').replace(/\/$/, '');
const webDir = path.resolve(import.meta.dirname, '..');
const imageDir = path.join(webDir, 'public', 'demo');
const fixturesFile = path.join(webDir, 'src', 'demo', 'fixtures.ts');

/** Same values the public pages use (lib/public-api.ts and the pages that call it). */
const MEDIA_PAGE_SIZE = 24;
const TESTIMONIAL_PAGE_SIZES = [8, 12];

async function get(pathAndQuery) {
  const response = await fetch(`${base}/api${pathAndQuery}`, { headers: { Accept: 'application/json' } });
  if (!response.ok) throw new Error(`GET ${pathAndQuery} answered ${response.status}`);
  return response.json();
}

const isMedia = (value) => value && typeof value === 'object' && typeof value.kind === 'string' && value.urls && typeof value.urls === 'object';

/** Removes videos and token-like fields, everywhere in the value. */
function clean(value) {
  if (Array.isArray(value)) return value.filter((item) => !(isMedia(item) && item.kind !== 'PHOTO')).map(clean);
  if (!value || typeof value !== 'object') return value;
  const out = {};
  for (const [key, child] of Object.entries(value)) {
    if (/token/i.test(key)) continue;
    out[key] = isMedia(child) && child.kind !== 'PHOTO' ? null : clean(child);
  }
  return out;
}

/** One page holding only what was captured, so the page never asks for a next one. */
function onePage(page) {
  return { ...page, page: 1, totalPages: 1, total: page.items.length };
}

const files = new Map();

async function download(url, name) {
  const response = await fetch(`${base}${url}`);
  if (!response.ok) throw new Error(`GET ${url} answered ${response.status}`);
  const type = response.headers.get('content-type') ?? '';
  const ext = type.includes('webp') ? 'webp' : type.includes('png') ? 'png' : 'jpg';
  const file = `${name}.${ext}`;
  fs.writeFileSync(path.join(imageDir, file), Buffer.from(await response.arrayBuffer()));
  return `/demo/${file}`;
}

/** Copies each photo's thumb and medium once and points its URLs at the copies (original uses medium). */
async function localiseMedia(value) {
  if (Array.isArray(value)) {
    for (const item of value) await localiseMedia(item);
    return;
  }
  if (!value || typeof value !== 'object') return;
  if (isMedia(value)) {
    const name = value.id.slice(0, 8);
    if (!files.has(name)) {
      const thumb = value.urls.thumb ? await download(value.urls.thumb, `${name}-thumb`) : null;
      const medium = value.urls.medium ? await download(value.urls.medium, `${name}-medium`) : null;
      files.set(name, { thumb: thumb ?? medium, medium: medium ?? thumb });
    }
    const local = files.get(name);
    value.urls = { thumb: local.thumb, medium: local.medium, original: local.medium };
    return;
  }
  for (const child of Object.values(value)) await localiseMedia(child);
}

const site = await get('/site');
const timeline = await get('/timeline');
const family = await get('/family');
const albums = await get('/albums');
const programme = await get('/programme');
const rsvpForm = await get('/rsvp/form');
const albumDetails = {};
const albumMedia = {};
for (const album of albums) {
  albumDetails[album.slug] = await get(`/albums/${encodeURIComponent(album.slug)}`);
  albumMedia[album.slug] = await get(`/media?album=${encodeURIComponent(album.slug)}&page=1&pageSize=${MEDIA_PAGE_SIZE}`);
}
const testimonials = {};
for (const size of TESTIMONIAL_PAGE_SIZES) testimonials[size] = await get(`/testimonials/public?page=1&pageSize=${size}`);

const data = clean({ site: { ...site, isDemo: true }, timeline, family, albums, albumDetails, albumMedia, programme, testimonials, rsvpForm });
for (const slug of Object.keys(data.albumMedia)) data.albumMedia[slug] = onePage(data.albumMedia[slug]);
for (const size of Object.keys(data.testimonials)) data.testimonials[size] = onePage(data.testimonials[size]);

fs.rmSync(imageDir, { recursive: true, force: true });
fs.mkdirSync(imageDir, { recursive: true });
await localiseMedia(data);

const json = (value) => JSON.stringify(value, null, 2);
if (json(data).includes('/api/')) throw new Error('An /api/ URL is left in the captured data; extend localiseMedia.');

const source = `// Generated by apps/web/scripts/capture-demo.mjs from ${base}. Do not edit by hand; run the script again.
import type {
  AlbumDetail,
  AlbumSummary,
  FamilyTree,
  Paginated,
  ProgrammeGroup,
  PublicMedia,
  PublicTestimonial,
  RsvpFormConfig,
  SiteOverview,
  TimelineEntry,
} from '@birthday/types';

export const site: SiteOverview = ${json(data.site)};

export const timeline: TimelineEntry[] = ${json(data.timeline)};

export const family: FamilyTree = ${json(data.family)};

export const albums: AlbumSummary[] = ${json(data.albums)};

export const albumDetails: Record<string, AlbumDetail> = ${json(data.albumDetails)};

/** First page of each album's photos, by slug. */
export const albumMedia: Record<string, Paginated<PublicMedia>> = ${json(data.albumMedia)};

/** Programme items grouped by public event. */
export const programme: ProgrammeGroup[] = ${json(data.programme)};

/** First page of the public tributes, by page size. */
export const testimonials: Record<number, Paginated<PublicTestimonial>> = ${json(data.testimonials)};

export const rsvpForm: RsvpFormConfig = ${json(data.rsvpForm)};
`;
fs.mkdirSync(path.dirname(fixturesFile), { recursive: true });
fs.writeFileSync(fixturesFile, source);

const bytes = fs.readdirSync(imageDir).reduce((sum, file) => sum + fs.statSync(path.join(imageDir, file)).size, 0);
console.log(`Wrote ${path.relative(process.cwd(), fixturesFile)} and ${files.size} photos (${(bytes / 1024).toFixed(0)} KB) to ${path.relative(process.cwd(), imageDir)}/`);
